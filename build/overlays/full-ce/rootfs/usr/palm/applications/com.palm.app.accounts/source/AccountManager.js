enyo.kind({
	name: "AccountManager",
	kind: "Pane",
	flex:1,
	capability: undefined,
	components: [
		// The first view shows "Loading Accounts ..."
		{kind: "VFlexBox", name: "loadingAccounts", className:"enyo-bg", components: [
		{kind:"Toolbar", className:"enyo-toolbar-light accounts-header", pack:"center", components: [
				{kind: "Image", src: "images/acounts-48x48.png"},
				{kind: "Control", content: AccountsUtil.PAGE_TITLE_ACCOUNTS}
			]},
			{className:"accounts-header-shadow"},
			{kind: "HFlexBox", className:"box-center", flex:1, pack:"center", align:"center", components: [
				{kind:"Spinner", name: "getAccountsSpinner"},
				{content: $L("Loading Accounts...")}
			]},
		]},
		// The second view is the main Accounts view
		{kind: "VFlexBox", name: "prefsAndAccounts", className:"enyo-bg", components: [
			{kind:"Toolbar", className:"enyo-toolbar-light accounts-header", pack:"center", components: [
				{kind: "Image", src: "images/acounts-48x48.png"},
				{kind: "Control", content: AccountsUtil.PAGE_TITLE_ACCOUNTS}
			]},
			{className:"accounts-header-shadow"},
			{kind: "Scroller", flex: 1, components: [
				{kind:"Control", className:"box-center", components: [
					{kind: "RowGroup", name: "palmProfileGroup", className:"accounts-group", caption:$L("Local Account"), components: [
						// Stays disabled unless a profile service actually answers - see
						// probeProfileService(). On a device with no Palm Profile replacement this
						// is exactly the previous behaviour: a non-tappable label.
						{kind: "Item", name: "palmProfileItem", layoutKind: "HFlexLayout", tapHighlight: true, disabled:true, className:"enyo-single" , onclick: "editPalmidProfile", align:"center", components:[
							{kind: "Image", name: "profileIcon", className:"icon-image"},
							{name:"palmProfileName", className:"enyo-text-ellipsis", flex:1}
						]}
					]},                                        
					{kind: "Control", name: "synergyAccounts", components: [
						// This is the one-line kind to get the list of accounts.  It is initialized in your create method below                                 
						{kind: "RowGroup", className:"accounts-group", name: "synergyAccountGroup", caption: $L("SYNERGY ACCOUNTS"), components: [
							{kind: "Accounts.accountsList", name: "accountsList", grouped: false, groupTitle: $L("SYNERGY ACCOUNTS"), onAccountsList_AccountSelected: "editAccount", onAccountsList_Ready: "listReady" }
						]},
					]},
					{kind: "RowGroup", className:"accounts-group", name: "simAccountGroup", components: [
						{kind: "Accounts.accountsList", name: "SIMAccountsList", onAccountsList_AccountSelected: "editAccount", onAccountsList_Ready: "listReady"}
					]},
					// You'll probably want an "Add Account" button
					{kind: "Button", label: $L("Add an Account"), className:"enyo-button-dark accounts-btn", onclick: "AddAccount"}
				]}
			]},
		]},
		// This kind controls the view when a user is adding  an account.  You should switch to this view when
		// the user taps on the "Add Account" button and return to the "prefsAndAccounts" view when
		// onAccountsUI_Done event is received
		{kind: "AccountsUI", name: "AccountsView", lazy:true, capability: this.capability, onAccountsUI_Done: "accountsDone"},

		// If your app is 'EMAIL' then you need to define your "Edit account" view here.  Otherwise use this view
		// "components" is optional, but it allows you to specify additional preferences on the page that will appear
		// under the "Remove Account" button.  All events generated by these components are forwarded to your app.
		{kind: "AccountsModify", name: "AccountsModify", lazy:true, capability: this.capability, onAccountsModify_Done: "accountsDone"},

		{kind: "MyApps.PalmID",  name: "palmprofile", lazy:true, capability: this.capability, onAccountsModify_Done: "accountsDone"},
		{kind: "Accounts.RetainedDataView", name: "retainedDataView", lazy:true, onRetainedData_Done: "accountsDone"},
		{kind: "Accounts.getAccounts", name: "accounts", onGetAccounts_AccountsAvailable: "onAccountsAvailable"},
		{kind:"VFlexBox", components: [
			{name: "appMenu", kind: "AppMenu", components: [
				{name: "deleteDataMenuItem", caption: $L("Delete Account Data"), onclick: "showRetainedData", showing: false},
				{kind: "HelpMenu", target: "http://help.palm.com/accountsmgr/index.html"}
			]},
		]},
		
		{kind: "PalmService", name: "getPalmProfileAccountInfo", service: "palm://com.palm.accountservices/", method: "getAccountInfo", onSuccess: "setPalmProfileNameSuccess"},
		// Capability probe for the profile editor. getAccountToken is local-only (it reads the
		// stored profile out of db8, no network), so it answers fast and tells us two things at
		// once: whether a Palm Profile replacement service is on the bus at all, and whether an
		// account is actually signed in on this device. Either failure leaves the row disabled.
		{kind: "PalmService", name: "probeProfileToken", service: "palm://com.palm.accountservices/", method: "getAccountToken", onSuccess: "profileServiceAvailable", onFailure: "profileServiceUnavailable"},
		{kind: "PalmService", name: "modifyPalmProfileAccountName", service: enyo.palmServices.accounts, method: "modifyAccount"},
		{kind: "PalmService", name: "retainedQuery", service: "palm://com.palm.db/", method: "find", onSuccess: "gotRetainedData", onFailure: "gotRetainedData"},
	],
	
	create: function() {
		this.inherited(arguments);
		
		// Setup the Accounts and SIM lists first so that they are available as soon and the view renders
		this.lists = 0;
		this.$.accountsList.getAccountsList(this.capability, ['com.palm.palmprofile', 'com.palm.sim']);
		this.$.SIMAccountsList.getAccountsList('com.palm.sim');
		
		// Start the spinner
		this.$.getAccountsSpinner.show();

		// Handle a deep-link launch param (e.g. Phone prefs -> manage a specific account). On a fresh
		// launch enyo's windowParamsChangeHandler wiring doesn't reach this app root, so read PalmSystem
		// launch params directly here; onAccountsAvailable() acts on them once the account list loads.
		try {
			var lp = (window.PalmSystem && PalmSystem.launchParams) ? enyo.json.parse(PalmSystem.launchParams) : null;
			if (lp && lp.accountId) {
				if (lp.launchType === "modifyAccount") {
					console.log("Accounts app: deep-link modify account " + lp.accountId);
					this.modifyAccountId = lp.accountId;
				} else if (lp.launchType === "changelogin") {
					console.log("Accounts app: deep-link change credentials " + lp.accountId);
					this.changeLoginAccountId = lp.accountId;
				}
			}
		} catch (e) {
			console.log("Accounts app: launchParams parse error: " + e);
		}
	},
	
	listReady: function () {
		// One of the Accounts or SIM lists is ready to be rendered
		this.lists++;
		
		// If both lists are ready, get the list of accounts so that the entire view can be drawn
		if (this.lists === 2)
			this.$.accounts.getAccounts();
	},
	
	// App was launched to change credentials
	windowParamsChangeHandler: function(inSender, inEvent) {
		// enyo may invoke this as (params) [enyo.call convention, params is the first arg] or as
		// (inSender, {params}) [ApplicationEvents convention]. Read whichever form arrived.
		var p = (inEvent && inEvent.params) || (inSender && inSender.params) || inSender || {};
		if (p && p.launchType === "changelogin" && p.accountId) {
			console.log("Accounts app: Change credentials for " + p.accountId);
			// Wait until all the accounts are retrieved before acting on this information
			this.changeLoginAccountId = p.accountId;
		}
		else if (p && p.launchType === "modifyAccount" && p.accountId) {
			// Deep-link (e.g. from Phone prefs) to manage/remove a specific account. Acted on once the
			// account list has loaded (see onAccountsAvailable).
			console.log("Accounts app: Modify account " + p.accountId);
			this.modifyAccountId = p.accountId;
		}
	},

	// App was already running when credential dashboard was tapped
	applicationRelaunchHandler: function(inSender, inEvent) {
		// enyo may invoke this as (params) [enyo.call convention, params is the first arg] or as
		// (inSender, {params}) [ApplicationEvents convention]. Read whichever form arrived.
		var p = (inEvent && inEvent.params) || (inSender && inSender.params) || inSender || {};
		if (p && p.launchType === "changelogin" && p.accountId) {
			console.log("Accounts app: Change credentials for " + p.accountId);
			
			// Are the accounts available?
			if (this.accounts) {
			// Find the account
				for (var i=0, l=this.accounts.length; i<l; i++) {
					if (this.accounts[i]._id === p.accountId) {
						this.selectViewByName("AccountsModify");
						this.$.AccountsModify.ModifyCredentials(this.accounts[i]);
					}
				}			
			}
			else {
				// Wait until all the accounts are retrieved before acting on this information
				this.changeLoginAccountId = p.accountId;
			}
		}
		else if (p && p.launchType === "modifyAccount" && p.accountId) {
			// Deep-link to manage/remove a specific account. Open its full modify view (with Remove) now if
			// the accounts are loaded, otherwise defer to onAccountsAvailable.
			console.log("Accounts app: Modify account " + p.accountId);
			if (this.accounts) {
				for (var i=0, l=this.accounts.length; i<l; i++) {
					if (this.accounts[i]._id === p.accountId) {
						this.selectViewByName("AccountsModify");
						this.$.AccountsModify.ModifyAccount(this.accounts[i]);
					}
				}
			}
			else {
				this.modifyAccountId = p.accountId;
			}
		}
	},

	onAccountsAvailable: function(inSender, inResponse) {
		this.accounts = inResponse.accounts;    // Accounts are returned as an array
		this.templates = inResponse.templates;
		var simAccounts = 0;
		
		// Separate the Profile and SIM accounts from the others
		this.accounts = this.accounts.filter(function(account) {
			if (account.templateId === "com.palm.palmprofile") {
				if (this.palmProfileAccount === undefined)  {
					//Jira: CWS-4249
					//We just want to reset the account name if for some reason it changed on the server. 
					//FIXME: We don't have a Palm Profile or similar functionality yet, so we skip this call, since we don't have palm://com.palm.accountservices/ available either
					//This otherwise would give the following error in the logs: ls-hubd.private LSHUB_NOT_LSTED {"SERVICE_NAME":"com.palm.accountservices","EXE":"/usr/lib/qt5/libexec/QtWebEngineProcess","APP_ID":"com.palm.app.accounts 1006","PID":1147} Service not listed in service files (cmdline: /usr/lib/qt5/libexec/QtWebEngineProcess --type=renderer --disable-accelerated-video-decode --enable-overlay-scrollbar --enable-pinch --enable-threaded-compositing --enable-viewport --enable-viewport-meta --main-frame-resizes-are-orientation-changes --no-sandbox --profiler-timing=0 --use-gl=egl --disable-composited-antialiasing --lang=en --enable-pinch --enable-delegated-renderer --num-raster-threads=1 --gpu-rasterization-msaa-sample-count=8 )
					//this.$.getPalmProfileAccountInfo.call({});
				}
				this.palmProfileAccount = account;
				this.$.probeProfileToken.call({});

				return false;
			}
			if (account.templateId === "com.palm.sim") {
				simAccounts++;
				return false;
			}
			return true;
		}.bind(this));
		
		// Update the Profile username and icon
		this.$.palmProfileName.setContent(enyo.string.escapeHtml(this.palmProfileAccount.username));
		this.$.profileIcon.src = this.palmProfileAccount.icon.loc_32x32;
		this.$.profileIcon.srcChanged();
		
		// Change the SIM header based on the number of SIM Accounts
		if (simAccounts === 0)
			this.$.simAccountGroup.hide();
		else {
			this.$.simAccountGroup.show();
			var t = new enyo.g11n.Template($L("1#SIM ACCOUNT|#SIM ACCOUNTS"));
			this.$.simAccountGroup.setCaption(t.formatChoice(simAccounts, {}));
		}
		
		// Show the list of accounts if more than 1 account
		if (this.accounts.length >= 1)
			this.$.synergyAccounts.show();
		else
			this.$.synergyAccounts.hide();

		// Only offer "Delete Account Data" in the app menu if there are retained-data markers for accounts
		// that are not currently active (re-added accounts don't count).
		this.checkRetainedData();

		// Was the accounts app launched to change credentials?
		if (this.changeLoginAccountId || this.modifyAccountId) {
			// Deep-linked to a specific account: modifyAccountId opens the full modify view (with Remove);
			// changeLoginAccountId opens the credentials view. modifyAccount wins if somehow both are set.
			var _targetId = this.modifyAccountId || this.changeLoginAccountId;
			var _fullModify = !!this.modifyAccountId;
			delete this.changeLoginAccountId;
			delete this.modifyAccountId;
			// Find the account
			for (var i=0, l=this.accounts.length; i<l; i++) {
				if (this.accounts[i]._id === _targetId) {
					this.selectViewByName("AccountsModify");
					if (_fullModify)
						this.$.AccountsModify.ModifyAccount(this.accounts[i]);
					else
						this.$.AccountsModify.ModifyCredentials(this.accounts[i]);
					break;
				}
			}
		}
		else {
			// Go to the Accounts view, if the current view is "Loading Accounts"
			if (this.getViewName() === "loadingAccounts") {
				this.selectViewByName("prefsAndAccounts");

				// Prepare other views so they are ready when the user needs them
				setTimeout(enyo.bind(this, "PrepareViews"), 500);
			}
		}
	},
	
	// Prepare the other views for display
	PrepareViews: function() {
		this.$.getAccountsSpinner.hide();
		this.validateView("AccountsView");
		this.validateView("AccountsModify");
	},

	// "Add Account" button was tapped
	AddAccount: function(button) {
		this.selectViewByName("AccountsView");
		this.$.AccountsView.AddAccount(this.templates);
	},
	
	// A profile service answered with a token: this device has a real, signed-in account, so
	// the profile editor behind the row has something to edit. Enable it and drop the
	// "Local Account" wording, which is only accurate when there is no backing service.
	profileServiceAvailable: function(inSender, inResponse) {
		if (!inResponse || !inResponse.token) {
			return;
		}
		this.$.palmProfileItem.setDisabled(false);
		this.$.palmProfileGroup.setCaption($L("ACCOUNT"));
	},

	profileServiceUnavailable: function(inSender, inResponse) {
		// Expected on any device without a Palm Profile replacement, on a device where
		// nobody has signed in yet, and after a sign-out. Set the state rather than
		// just leaving the default, because this also runs on the way back from the
		// profile view, where the row may currently be enabled.
		console.log("Accounts app: no profile service/token, profile editor disabled");
		this.$.palmProfileItem.setDisabled(true);
		this.$.palmProfileGroup.setCaption($L("Local Account"));
		// The row label needs no special-casing: sign-out renames the local account
		// record to "Local User", so what is stored is already what should be shown.
	},


	editPalmidProfile:  function(inSender, inResults) {
		console.log("editPalmidProfile")
		this.selectViewByName("palmprofile");
		this.$.palmprofile.initialize({palmProfileAccount: this.palmProfileAccount});
	},
	
	setPalmProfileNameSuccess: function(inSender, inResponse) {
		console.log("setPalmProfileNameSuccess");
		var accountName = inResponse.firstName + " " + inResponse.lastName;
		
		var param = {
			"accountId": this.palmProfileAccount._id,
			"object": {"username": accountName}
		}
		
		console.log("PalmProfileName: " + JSON.stringify(param));
		// Modify the account
		this.$.modifyPalmProfileAccountName.call(param);
    },

		
	// User tapped on account to edit
	editAccount: function(inSender, inResults) {
		this.selectViewByName("AccountsModify");
		this.$.AccountsModify.ModifyAccount(inResults.account);
	},
	
	// Go to the prefs and accounts view
	accountsDone: function(inSender, e) {
		this.selectViewByName("prefsAndAccounts");
		// Re-probe on the way back: the user may have just signed out, in which
		// case the row has to stop being tappable or the next tap walks into a
		// profile fetch with no token behind it.
		this.$.probeProfileToken.call({});
	},

	// App menu -> "Delete Account Data": open the retained-data page (swipe-to-delete list of accounts
	// that were removed with their data kept on the device).
	showRetainedData: function() {
		this.$.appMenu.close();
		this.selectViewByName("retainedDataView");
		// Pass the active accounts too so a re-added account is filtered out of the delete list.
		this.$.retainedDataView.load(this.templates, this.accounts);
	},

	// Query the retained-data markers and show the "Delete Account Data" menu item only if any belong to
	// an account that is NOT currently active (a re-added account's marker doesn't count).
	checkRetainedData: function() {
		this.$.retainedQuery.call({query: {from: "com.palm.imretaineddata:1"}});
	},
	gotRetainedData: function(inSender, resp) {
		var results = (resp && resp.results) || [];
		var active = {}, i;
		for (i = 0; i < this.accounts.length; i++) {
			var a = this.accounts[i];
			if (a && a.templateId)
				active[this.retainedKey(a.templateId, a.username)] = true;
		}
		var count = 0;
		for (i = 0; i < results.length; i++) {
			if (!active[this.retainedKey(results[i].templateId, results[i].username)])
				count++;
		}
		var _mi = this.$.deleteDataMenuItem || (this.$.appMenu && this.$.appMenu.$ && this.$.appMenu.$.deleteDataMenuItem);
		if (_mi) { _mi.setShowing(count > 0); }
	},
	retainedKey: function(templateId, username) {
		return (templateId || "") + "|" + String(username || "").toLowerCase().replace(/[^a-z0-9]/g, "");
	},

	// App menu -> "Delete Account Data": open the retained-data page (swipe-to-delete list of accounts
	// that were removed with their data kept on the device).
	showRetainedData: function() {
		this.$.appMenu.close();
		this.selectViewByName("retainedDataView");
		// Pass the active accounts too so a re-added account is filtered out of the delete list.
		this.$.retainedDataView.load(this.templates, this.accounts);
	},

	// Query the retained-data markers and show the "Delete Account Data" menu item only if any belong to
	// an account that is NOT currently active (a re-added account's marker doesn't count).
	checkRetainedData: function() {
		this.$.retainedQuery.call({query: {from: "com.palm.imretaineddata:1"}});
	},
	gotRetainedData: function(inSender, resp) {
		var results = (resp && resp.results) || [];
		var active = {}, i;
		for (i = 0; i < this.accounts.length; i++) {
			var a = this.accounts[i];
			if (a && a.templateId)
				active[this.retainedKey(a.templateId, a.username)] = true;
		}
		var count = 0;
		for (i = 0; i < results.length; i++) {
			if (!active[this.retainedKey(results[i].templateId, results[i].username)])
				count++;
		}
		var _mi = this.$.deleteDataMenuItem || (this.$.appMenu && this.$.appMenu.$ && this.$.appMenu.$.deleteDataMenuItem);
		if (_mi) { _mi.setShowing(count > 0); }
	},
	retainedKey: function(templateId, username) {
		return (templateId || "") + "|" + String(username || "").toLowerCase().replace(/[^a-z0-9]/g, "");
	},
	
	// Open or close the App Menu
	openAppMenuHandler: function() {
		this.$.appMenu.open();
	},
	closeAppMenuHandler: function() {
		this.$.appMenu.close();
	}	
});

